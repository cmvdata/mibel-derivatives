def representative_year_profile(
    config: str = "fixed_35deg_south",
    *,
    panel=None,  # type: ignore[no-untyped-def]  # pd.DataFrame | None
) -> np.ndarray:
    """Build an 8760-hour capacity-factor profile from the PVGIS panel.

    Averages the per-hour capacity factor (``p_w / 1000`` for the 1 kWp
    reference) across the available years for ``config``, indexed by
    (month, day-of-year-hour) so the diurnal and seasonal shape survive.
    The result is a deterministic "typical year" hourly profile in
    ``[0, 1]`` suitable for :func:`price_ppa`.

    Loads the curated parquet lazily when ``panel`` is not supplied so the
    module imports cleanly without the data present.
    """
    if panel is None:
        import pandas as pd

        from mibel_derivatives.data import _paths

        panel = pd.read_parquet(_paths.curated_path("pvgis_panel.parquet"))

    sub = panel[panel["config"] == config].copy()
    if sub.empty:
        raise ValueError(f"no rows for config={config!r} in the PVGIS panel")

    dt = sub["dt_utc"]
    # Group by (month, day, hour) and average across years; drop Feb-29 so
    # every typical year is 8760 hours.
    key_month = dt.dt.month
    key_day = dt.dt.day
    key_hour = dt.dt.hour
    sub = sub.assign(_m=key_month, _d=key_day, _h=key_hour)
    sub = sub[~((sub["_m"] == 2) & (sub["_d"] == 29))]
    cf = (sub["p_w"] / 1000.0).clip(lower=0.0, upper=1.0)
    sub = sub.assign(_cf=cf)
    typical = (
        sub.groupby(["_m", "_d", "_h"], sort=True)["_cf"]
        .mean()
        .sort_index()
        .to_numpy()
    )
    return typical.astype(float)


