def _annuity_factor(rate: float, duration_years: int) -> float:
    """Present value of one unit of annual cashflow received mid-year for
    ``duration_years`` years at a flat ``rate``.

    Mid-year discounting (exponent ``y - 0.5``) is the standard convention
    for cashflows that accrue continuously through the delivery year."""
    years = np.arange(1, duration_years + 1)
    return float(np.sum((1.0 + rate) ** -(years - 0.5)))


def price_ppa(
    ppa: PPA,
    *,
    pv_profile: np.ndarray | None = None,
    price_model: PriceModel | None = None,
    price_paths: np.ndarray | None = None,
    production_paths: np.ndarray | None = None,
    n_paths: int = DEFAULT_N_PATHS,
    discount_rate: float = DEFAULT_DISCOUNT_RATE,
    resource_sigma: float = 0.05,
    hourly_sigma: float = 0.0,
    seed: int | None = None,
) -> PPAResult:
    """Price a solar PPA by Monte Carlo with capture-price decomposition.

    Parameters
    ----------
    ppa
        :class:`PPA` contract terms.
    pv_profile
        Hourly capacity-factor profile in ``[0, 1]`` for one contract year
        (typically 8760 values from the curated PVGIS panel). Required
        unless both ``price_paths`` and ``production_paths`` are supplied.
    price_model
        :class:`PriceModel` for the internal reduced-form price generator.
        Defaults to ``PriceModel()`` when ``price_paths`` is not supplied.
    price_paths, production_paths
        Optional pre-simulated paths, each shape ``(n_paths, n_hours)``
        (EUR/MWh and MWh respectively). When supplied they are used
        verbatim — this is the path-agnostic mode used by the tests and by
        an OMIP-consistent reported valuation. The two must agree on shape.
    n_paths
        Monte Carlo paths when generating internally. Ignored for any
        factor whose paths are supplied.
    discount_rate
        Flat real annual discount rate for the multi-year PV.
    resource_sigma, hourly_sigma
        Generation-noise parameters forwarded to
        :func:`simulate_production_paths`.
    seed
        Reproducibility. A single seed drives both internal generators with
        independent sub-streams (price seed ``seed``, production seed
        ``seed + 1``) so the two factors are not spuriously correlated.

    Returns
    -------
    PPAResult
        Present value (EUR), levelised value (EUR/MWh), capture-price
        diagnostics and per-path values.

    Notes
    -----
    The per-hour cashflow is the brief's formula::

        payoff_h = generation_h * (strike*fixed_pct + spot_h*spot_pct - cost)

    summed to an annual cashflow per path and present-valued over the
    contract with the mid-year annuity factor. v1 treats each contract year
    as drawing the same annual scenario (the per-path annual cashflow times
    the annuity factor); interannual resampling is a documented extension.
    """
    # ---- resolve / generate the two factor path sets ----------------------
    if price_paths is not None or production_paths is not None:
        if price_paths is None or production_paths is None:
            raise ValueError(
                "supply both price_paths and production_paths, or neither"
            )
        price = np.asarray(price_paths, dtype=float)
        gen = np.asarray(production_paths, dtype=float)
        if price.ndim != 2 or gen.ndim != 2:
            raise ValueError("price_paths and production_paths must be 2D")
        if price.shape != gen.shape:
            raise ValueError(
                f"path shapes differ: price {price.shape} vs production {gen.shape}"
            )
        if not (np.isfinite(price).all() and np.isfinite(gen).all()):
            raise ValueError("supplied paths contain non-finite values")
    else:
        if pv_profile is None:
            raise ValueError(
                "pv_profile is required unless both path arrays are supplied"
            )
        cf = _normalise_profile(pv_profile)
        model = price_model if price_model is not None else PriceModel()
        price_seed = seed
        prod_seed = None if seed is None else seed + 1
        price = simulate_price_paths(model, cf, n_paths, seed=price_seed)
        gen = simulate_production_paths(
            cf,
            ppa.capacity_mw,
            n_paths,
            resource_sigma=resource_sigma,
            hourly_sigma=hourly_sigma,
            seed=prod_seed,
        )

    n_paths_eff, n_hours = price.shape

    # ---- capture-price decomposition --------------------------------------
    total_gen = gen.sum(axis=1)                       # (n_paths,) MWh / year
    revenue_spot = (gen * price).sum(axis=1)          # (n_paths,) EUR / year
    safe_gen = np.where(total_gen > 0.0, total_gen, np.nan)
    capture_price = revenue_spot / safe_gen           # generation-weighted
    baseload_price = price.mean(axis=1)               # simple hourly mean

    # ---- PPA structured cashflow (brief's per-hour formula) ---------------
    # generation_h * (strike*fixed_pct + spot_h*spot_pct - cost), summed.
    annual_cashflow = (
        ppa.fixed_pct * ppa.strike * total_gen
        + ppa.spot_pct * revenue_spot
        - ppa.cost_ppa * total_gen
    )

    annuity = _annuity_factor(discount_rate, ppa.duration_years)
    per_path_value = annuity * annual_cashflow

    value = float(per_path_value.mean())
    std_error = (
        float(per_path_value.std(ddof=1) / np.sqrt(n_paths_eff))
        if n_paths_eff > 1
        else 0.0
    )

    pv_total_gen = annuity * float(total_gen.mean())
    value_per_mwh = value / pv_total_gen if pv_total_gen > 0.0 else float("nan")

    capture_mean = float(np.nanmean(capture_price))
    baseload_mean = float(baseload_price.mean())
    capture_ratio = capture_mean / baseload_mean if baseload_mean > 0.0 else float("nan")

    return PPAResult(
        value=value,
        std_error=std_error,
        value_per_mwh=value_per_mwh,
        capture_price_mean=capture_mean,
        baseload_price_mean=baseload_mean,
        capture_ratio=capture_ratio,
        annual_generation_mwh=float(total_gen.mean()),
        per_path_value=per_path_value,
        n_paths=n_paths_eff,
        n_hours=n_hours,
        duration_years=ppa.duration_years,
    )


